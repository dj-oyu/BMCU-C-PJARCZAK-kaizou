static const uint8_t kRowCount = 45;

inline void unpack(uint8_t idx, Row* out)
{
    const uint8_t* b = kRows[idx];
    const uint32_t bits = (uint32_t)b[9] | ((uint32_t)b[10] << 8);
    out->pressure = (uint16_t)(b[0] | (b[1] << 8));
    out->unknow2 = (uint16_t)(b[2] | (b[3] << 8));
    out->unknow3[0] = b[4];
    out->unknow3[1] = b[5];
    out->unknow3[2] = b[6];
    out->unknow3[3] = b[7];
    out->unknow3[4] = kU3_4[(bits >> 3) & 3u];
    out->unknow3[5] = 0xFFu;
    out->unknow3[6] = kU3_6[(bits >> 5) & 3u];
    out->unknow3[7] = 0xFFu;
    out->unknow3[8] = 0x00u;
    out->unknow3[9] = 0x00u;
    out->unknow3[10] = b[8];
    out->unknow3[11] = kU3_11[bits & 7u];
    out->last1 = 0xF3F4FA57u | ((bits & 0x80u) << 1);
    out->last2 = 0xB4B5EC00u + (((bits >> 8) & 7u) << 8) + 0xF6u + ((bits >> 11) & 1u);
}

