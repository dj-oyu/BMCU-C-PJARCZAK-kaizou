int main()
{
    const unsigned n = sizeof(kOriginal) / sizeof(kOriginal[0]);
    if (n != before_on_use_replay::kRowCount) return 1;
    for (unsigned i = 0; i < n; ++i)
    {
        before_on_use_replay::Row r;
        before_on_use_replay::unpack((uint8_t)i, &r);
        const OrigRow& o = kOriginal[i];
        if (r.pressure != o.pressure) return 10;
        if (r.unknow2 != o.unknow2) return 11;
        if (memcmp(r.unknow3, o.unknow3, 12) != 0) return 12;
        if (r.last1 != o.last1) return 13;
        if (r.last2 != o.last2) return 14;
    }
    return 0;
}
